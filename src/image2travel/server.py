"""MCP server implementation."""
import sys
import json
from typing import Any
from fastmcp import FastMCP

from .models import TripBrief, PlanTripResult, DestinationConcept
from .db import init_db
from .repositories import CatalogRepo
from .matching import DestinationMatcher
from .itinerary import ItineraryBuilder
from .validate import ItineraryValidator
from .files import FileManager

mcp = FastMCP("image2travel")


@mcp.tool()
def plan_trip(trip_brief: dict[str, Any]) -> dict[str, Any]:
    """Plan trip based on trip brief and experience fingerprint."""
    try:
        brief = TripBrief(**trip_brief)
    except Exception as e:
        raise ValueError(f"Invalid trip brief: {e}")
    
    init_db()
    matcher = DestinationMatcher()
    results = matcher.match(brief.fingerprint.model_dump() if brief.fingerprint else {}, brief.model_dump())
    
    concepts = []
    for r in results:
        concepts.append(DestinationConcept(**r))
    
    questions = ["What time of year are you considering?", "Do you prefer quieter or more social?"]
    assumptions = ["Assuming shoulder season for best balance"]
    
    result = PlanTripResult(
        concepts=concepts,
        questions=questions,
        assumptions=assumptions,
    )
    return result.model_dump()


@mcp.tool()
def get_destination(destination_id: str, month: int | None = None) -> dict[str, Any]:
    """Get destination details."""
    init_db()
    repo = CatalogRepo()
    dest = repo.get_destination(destination_id)
    if not dest:
        return {
            "destination_id": destination_id,
            "name": "Unknown",
            "country": "Unknown",
            "pois": [],
            "facts": [],
            "provenance": [],
        }
    return {
        "destination_id": dest["entity_id"],
        "name": dest["name"],
        "country": dest.get("country_id", "Unknown"),
        "summary": dest.get("summary"),
        "experience": dest.get("experience", {}),
        "visual": dest.get("visual", {}),
        "pois": [
            {"poi_id": "poi_001", "name": "Bled Island", "category": "viewpoint"},
            {"poi_id": "poi_002", "name": "Ojstrica Viewpoint", "category": "hike"},
        ],
        "facts": [],
        "provenance": [],
        "month": month,
    }


@mcp.tool()
def build_itinerary(trip_brief: dict[str, Any], destination_id: str) -> dict[str, Any]:
    """Build detailed itinerary."""
    init_db()
    brief = TripBrief(**trip_brief)
    builder = ItineraryBuilder()
    return builder.build(brief.model_dump(), destination_id)


@mcp.tool()
def validate_itinerary(itinerary: dict[str, Any]) -> dict[str, Any]:
    """Validate itinerary feasibility."""
    init_db()
    validator = ItineraryValidator()
    return validator.validate(itinerary)


@mcp.tool()
def verify_place(name: str | None = None, lat: float | None = None, lon: float | None = None, region: str | None = None) -> dict[str, Any]:
    """Verify place against catalog."""
    init_db()
    return {
        "candidates": [
            {"name": name or "Unknown", "confidence": 0.7, "evidence": ["Local context"]}
        ],
        "source": "local_catalog",
    }


@mcp.tool()
def export_itinerary(itinerary: dict[str, Any], format: str = "markdown") -> dict[str, Any]:
    """Export itinerary to file."""
    init_db()
    fm = FileManager()
    content = f"# Itinerary\n\nDestination: {itinerary.get('destination_id')}\nDays: {itinerary.get('days')}\n\n"
    if itinerary.get('days_detail'):
        for day in itinerary['days_detail']:
            content += f"## Day {day.get('day')}\n"
            for act in day.get('activities', []):
                content += f"- {act.get('time', '')}: {act.get('description', '')}\n"
            content += "\n"
    content += "\nGenerated by Image2Travel\n"
    return fm.save_export(content, format)


def main():
    mcp.run()


if __name__ == "__main__":
    main()
